#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md: the license of every package the app ships.

Run from the repository root after `npm ci` (cargo must be able to resolve the
lockfile offline):

    python3 scripts/third_party_notices.py > THIRD_PARTY_NOTICES.md

Rust: every crate in the normal dependency tree for both macOS targets of the
universal build. npm: every package in package-lock.json that is not dev only
(Vite bundles only what the code imports, so the shipped set is a subset).
License texts come from each package's own files; packages that carry the same
text are listed together under it.
"""
import glob
import json
import os
import subprocess
import sys

TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin"]
LICENSE_GLOBS = ["LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "license*", "UNLICENSE*"]


def license_files(folder):
    found = set()
    for g in LICENSE_GLOBS:
        for p in glob.glob(os.path.join(folder, g)):
            if os.path.isfile(p):
                found.add(p)
    return sorted(found)


def read_texts(folder):
    out = []
    for p in license_files(folder):
        with open(p, encoding="utf-8", errors="replace") as fh:
            out.append((os.path.basename(p), fh.read().strip()))
    return tuple(out)


def rust_packages():
    names = set()
    for t in TARGETS:
        tree = subprocess.run(
            ["cargo", "tree", "--offline", "--locked", "-e", "normal", "--target", t,
             "--prefix", "none", "--format", "{p}"],
            cwd="src-tauri", check=True, capture_output=True, text=True).stdout
        for line in tree.splitlines():
            parts = line.split()
            if len(parts) >= 2:
                names.add((parts[0], parts[1].lstrip("v")))
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--offline", "--locked", "--format-version", "1"]
        + [a for t in TARGETS for a in ("--filter-platform", t)],
        cwd="src-tauri", check=True, capture_output=True, text=True).stdout)
    root = {p["id"] for p in meta["packages"] if p["source"] is None}
    out = []
    for p in meta["packages"]:
        if (p["name"], p["version"]) in names and p["id"] not in root:
            folder = os.path.dirname(p["manifest_path"])
            out.append({"name": p["name"], "version": p["version"], "license": p.get("license") or "",
                        "where": "crates.io", "texts": read_texts(folder),
                        "repo": p.get("repository") or f"https://crates.io/crates/{p['name']}"})
    return sorted(out, key=lambda x: (x["name"], x["version"]))


def npm_packages():
    with open("package-lock.json", encoding="utf-8") as fh:
        lock = json.load(fh)
    out = []
    for path, info in lock["packages"].items():
        if not path or info.get("dev"):
            continue
        name = path.split("node_modules/")[-1]
        if not os.path.isdir(path):
            continue  # an optional package for another platform
        with open(os.path.join(path, "package.json"), encoding="utf-8") as fh:
            pkg = json.load(fh)
        lic = info.get("license") or pkg.get("license") or ""
        repo = pkg.get("repository") or ""
        if isinstance(repo, dict):
            repo = repo.get("url", "")
        repo = repo.removeprefix("git+").removesuffix(".git") or f"https://www.npmjs.com/package/{name}"
        out.append({"name": name, "version": info.get("version", ""), "license": lic,
                    "where": "npm", "texts": read_texts(path), "repo": repo})
    return sorted(out, key=lambda x: (x["name"], x["version"]))


def main():
    rust, npm = rust_packages(), npm_packages()
    allp = rust + npm
    w = sys.stdout.write
    w("# Third-party notices\n\n")
    w("Activity Ledger is MIT licensed (see LICENSE). It is built with the open source\n")
    w("packages below. Each keeps its own license; their texts follow.\n\n")
    w("This file is generated by `scripts/third_party_notices.py`. Do not edit it by hand.\n\n")
    w(f"Rust crates: {len(rust)}. npm packages: {len(npm)}.\n\n")

    mpl = [p for p in allp if "MPL" in p["license"]]
    if mpl:
        w("## MPL-2.0 packages\n\n")
        w("These are used unmodified. Their source code is available from crates.io:\n\n")
        for p in mpl:
            w(f"- {p['name']} {p['version']}: https://crates.io/crates/{p['name']}/{p['version']}\n")
        w("\n")

    w("## Packages\n\n| Package | Version | Source | License |\n|---|---|---|---|\n")
    for p in allp:
        w(f"| {p['name']} | {p['version']} | {p['where']} | {p['license'] or 'see text'} |\n")
    w("\n## License texts\n\n")

    # One section per distinct text (whitespace folded), naming every package
    # that ships it, so a common license text appears once.
    groups, keep = {}, {}
    for p in allp:
        for fname, body in p["texts"]:
            key = " ".join(body.split())
            keep.setdefault(key, body)
            groups.setdefault(key, []).append(f"{p['name']} {p['version']} ({fname})")
    for key, members in sorted(groups.items(), key=lambda kv: kv[1][0]):
        w("### " + ", ".join(members) + "\n\n")
        w(f"```\n{keep[key]}\n```\n\n")
    no_text = [p for p in allp if not p["texts"]]
    if no_text:
        w("### Packages that ship no license file\n\n")
        w("These declare their license in their manifest only. The standard text of\n")
        w("each license named is given above under another package. Their copyright\n")
        w("holders are named in their source, linked here.\n\n")
        for p in no_text:
            w(f"- {p['name']} {p['version']} ({p['where']}): {p['license']}. Source: {p['repo']}\n")
        w("\n")

if __name__ == "__main__":
    main()
